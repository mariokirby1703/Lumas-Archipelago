"""Read-only, dependency-free inventory of the user's local game files.

Run directly; deliberately does not import/register an unplayable AP world.
Proprietary strings and binary dumps remain under ignored notes/.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import struct
from pathlib import Path


def inspect_pe(data: bytes) -> dict:
    if len(data) < 64 or data[:2] != b"MZ":
        raise ValueError("Not a DOS/PE image")
    offset = struct.unpack_from("<I", data, 0x3C)[0]
    if offset + 24 > len(data) or data[offset:offset + 4] != b"PE\0\0":
        raise ValueError("Invalid PE header")
    machine, count, timestamp, _, _, optional_size, flags = struct.unpack_from("<HHIIIHH", data, offset + 4)
    optional = offset + 24
    if optional + optional_size + count * 40 > len(data):
        raise ValueError("Truncated PE headers")
    magic = struct.unpack_from("<H", data, optional)[0]
    if magic not in (0x10B, 0x20B):
        raise ValueError("Unsupported optional header")
    image_base = struct.unpack_from("<Q" if magic == 0x20B else "<I", data,
                                    optional + (24 if magic == 0x20B else 28))[0]
    sections = []
    for index in range(count):
        start = optional + optional_size + index * 40
        name, virtual_size, rva, size, raw = struct.unpack_from("<8sIIII", data, start)
        sections.append(dict(name=name.rstrip(b"\0").decode("ascii", "replace"),
                             virtual_size=virtual_size, rva=rva, raw_size=size, raw_offset=raw))
    return dict(machine=hex(machine), architecture={0x8664: "x64", 0x14C: "x86"}.get(machine, "unknown"),
                timestamp=timestamp, image_base=hex(image_base), characteristics=hex(flags), sections=sections)


def inventory(root: Path) -> list[dict]:
    entries = []
    for path in sorted(root.rglob("*")):
        if not path.is_file():
            continue
        digest = hashlib.sha256()
        with path.open("rb") as stream:
            header = stream.read(64)
            digest.update(header)
            while block := stream.read(8 * 1024 * 1024):
                digest.update(block)
        entry = dict(path=path.relative_to(root).as_posix(), size=path.stat().st_size,
                     extension=path.suffix.lower(), sha256=digest.hexdigest(), header_hex=header.hex())
        if header.startswith(b"MZ"):
            entry["pe"] = inspect_pe(path.read_bytes())
        entries.append(entry)
        print(entry["path"], entry["size"], flush=True)
    return entries


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    world = Path(__file__).resolve().parents[1]
    parser.add_argument("--root", type=Path, default=world / "notes/gamefiles")
    args = parser.parse_args()
    root = args.root.resolve(strict=True)
    output = world / "notes/analysis"
    output.mkdir(parents=True, exist_ok=True)
    entries = inventory(root)
    (output / "inventory.json").write_text(json.dumps(entries, indent=2), encoding="utf-8")
    for entry in entries:
        if "pe" in entry:
            data = (root / entry["path"]).read_bytes()
            strings = [dict(offset=match.start(), text=match.group().decode("ascii"))
                       for match in re.finditer(rb"[\x20-\x7e]{8,}", data)]
            (output / (entry["path"] + ".strings.json")).write_text(json.dumps(strings), encoding="utf-8")
    report = world / "docs/research/file_inventory.md"
    report.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Local game inventory", "", "Generated by `tools/inspect_game.py`; SHA-256 covers each full file.",
             "Original files were opened read-only. Binary headers and string dumps stay in ignored notes/analysis.",
             "", "| Path relative to notes/gamefiles | Bytes | SHA-256 | Type |", "|---|---:|---|---|"]
    for entry in entries:
        kind = entry.get("pe", {}).get("architecture", "unidentified; see analysis")
        lines.append(f"| {entry['path']} | {entry['size']} | `{entry['sha256']}` | {kind} |")
    report.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
